function studentsGrades(students) {
  const stats = {};

  for (let i = 0; i < students.length; i++) {
    const student = students[i];
    const { grade, subject } = student;

    if (typeof grade !== "number" || Number.isNaN(grade)) {
      console.log("Skipping invalid grade for:", student.name, "in", subject);
      continue;
    }
    if (!stats[subject]) {
      stats[subject] = { low: grade, high: grade, total: 0, count: 0 };
    }

    if (grade < stats[subject].low) {
      stats[subject]["low"] = grade;
    }
    if (grade > stats[subject].high) {
      stats[subject]["high"] = grade;
    }
    stats[subject]["count"]++;
    stats[subject]["total"] += grade;
  }

  for (let key in stats) {
    stats[key]["average"] = +(
      stats[key]["total"] / stats[key]["count"]
    ).toFixed(2);
    delete stats[key]["total"];
    delete stats[key]["count"];
  }
  return stats;
}

